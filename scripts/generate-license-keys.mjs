#!/usr/bin/env node
import { generateKeyPairSync } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

function parseArgs(argv) {
  const args = new Set(argv.slice(2));
  return {
    force: args.has('--force'),
    writePublicKey: args.has('--write-public-key')
  };
}

const { force, writePublicKey } = parseArgs(process.argv);

const keysDir = path.join(repoRoot, '.keys');
const privatePath = path.join(keysDir, 'ed25519-private.pem');
const publicPath = path.join(keysDir, 'ed25519-public.txt');
const tsPublicKeyPath = path.join(repoRoot, 'src/infrastructure/license-public-key.ts');

if (fs.existsSync(privatePath) && !force) {
  console.error(
    `Private key already exists at ${privatePath}. Refusing to overwrite without --force.`
  );
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519');
const privatePem = privateKey.export({ format: 'pem', type: 'pkcs8' }).toString();
const rawPublicBytes = publicKey.export({ format: 'der', type: 'spki' }).subarray(-32);
const publicB64Url = rawPublicBytes.toString('base64url');

fs.mkdirSync(keysDir, { recursive: true, mode: 0o700 });
fs.writeFileSync(privatePath, privatePem, { encoding: 'utf8', mode: 0o600 });
fs.chmodSync(privatePath, 0o600);
fs.writeFileSync(publicPath, `${publicB64Url}\n`, 'utf8');

console.log(`Generated Ed25519 keypair in ${keysDir}`);
console.log(`Public key (base64url): ${publicB64Url}`);

if (writePublicKey) {
  const tsContent = `// Auto-generated by scripts/generate-license-keys.mjs — DO NOT put private keys here.\nexport const PRODUCTION_LICENSE_PUBLIC_KEY_B64URL = '${publicB64Url}';\n`;
  fs.writeFileSync(tsPublicKeyPath, tsContent, 'utf8');
  console.log(`Updated ${tsPublicKeyPath}`);
}
